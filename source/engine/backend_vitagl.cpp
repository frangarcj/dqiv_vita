static GLuint MakeTexture(int w, int h, int fmt, const void* px) {
  GLuint id = 0;
  glGenTextures(1, &id);
  glBindTexture(GL_TEXTURE_2D, id); s_boundTex = ~0u;
  GLenum ifmt = GL_RGBA, f = GL_RGBA, type = GL_UNSIGNED_BYTE;
  switch (fmt) {
    case DQIV_TF_A8:       ifmt = f = GL_ALPHA; break;
    case DQIV_TF_RGB565:   ifmt = f = GL_RGB; type = GL_UNSIGNED_SHORT_5_6_5; break;
    case DQIV_TF_RGBA4444: type = GL_UNSIGNED_SHORT_4_4_4_4; break;
    case DQIV_TF_RGBA8888: default: break;
  }
  glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
  glTexImage2D(GL_TEXTURE_2D, 0, ifmt, w, h, 0, f, type, px);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
  return id;
}

static const int kCgCount = 3;           // OP_GRAY, OP_SEPIA_FLD, OP_SLEEP
