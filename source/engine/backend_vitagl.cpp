static void SetCombine(GLint rgbFn, GLint rs0, GLint ro0, GLint rs1, GLint ro1, GLint aFn, GLint as0, GLint ao0, GLint as1, GLint ao1) {
  glTexEnvi(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_COMBINE);
  glTexEnvi(GL_TEXTURE_ENV, GL_COMBINE_RGB, rgbFn);
  glTexEnvi(GL_TEXTURE_ENV, GL_SRC0_RGB, rs0); glTexEnvi(GL_TEXTURE_ENV, GL_OPERAND0_RGB, ro0);
  glTexEnvi(GL_TEXTURE_ENV, GL_SRC1_RGB, rs1); glTexEnvi(GL_TEXTURE_ENV, GL_OPERAND1_RGB, ro1);
  glTexEnvi(GL_TEXTURE_ENV, GL_COMBINE_ALPHA, aFn);
  glTexEnvi(GL_TEXTURE_ENV, GL_SRC0_ALPHA, as0); glTexEnvi(GL_TEXTURE_ENV, GL_OPERAND0_ALPHA, ao0);
  glTexEnvi(GL_TEXTURE_ENV, GL_SRC1_ALPHA, as1); glTexEnvi(GL_TEXTURE_ENV, GL_OPERAND1_ALPHA, ao1);
}

// Fixed-function realisation of the fragment op (04_SHADERS §1) for a textured draw.
static void SetupTexEnv(int op) {
  if (op == s_envOp) return;
  s_envOp = op;
  switch (op) {
    case OP_A8:       // (C.rgb, C.a * tex.a)  -- independent of the texture format
      SetCombine(GL_REPLACE, GL_PRIMARY_COLOR, GL_SRC_COLOR, GL_PRIMARY_COLOR, GL_SRC_COLOR,
                 GL_MODULATE, GL_TEXTURE, GL_SRC_ALPHA, GL_PRIMARY_COLOR, GL_SRC_ALPHA); break;
    case OP_RGB_A1:   // (tex.rgb * C.rgb, C.a)
      SetCombine(GL_MODULATE, GL_TEXTURE, GL_SRC_COLOR, GL_PRIMARY_COLOR, GL_SRC_COLOR,
                 GL_REPLACE, GL_PRIMARY_COLOR, GL_SRC_ALPHA, GL_PRIMARY_COLOR, GL_SRC_ALPHA); break;
    case OP_INV_A:    // (C.rgb, (1 - tex.a) * C.a)
      SetCombine(GL_REPLACE, GL_PRIMARY_COLOR, GL_SRC_COLOR, GL_PRIMARY_COLOR, GL_SRC_COLOR,
                 GL_MODULATE, GL_TEXTURE, GL_ONE_MINUS_SRC_ALPHA, GL_PRIMARY_COLOR, GL_SRC_ALPHA); break;
    case OP_POST_A:   // (C.rgb, tex.a * C.a)
      SetCombine(GL_REPLACE, GL_PRIMARY_COLOR, GL_SRC_COLOR, GL_PRIMARY_COLOR, GL_SRC_COLOR,
                 GL_MODULATE, GL_TEXTURE, GL_SRC_ALPHA, GL_PRIMARY_COLOR, GL_SRC_ALPHA); break;
    case OP_INVERT:   // (1 - tex.rgb, tex.a)
      SetCombine(GL_REPLACE, GL_TEXTURE, GL_ONE_MINUS_SRC_COLOR, GL_PRIMARY_COLOR, GL_SRC_COLOR,
                 GL_REPLACE, GL_TEXTURE, GL_SRC_ALPHA, GL_PRIMARY_COLOR, GL_SRC_ALPHA); break;
    default:          // MUL, LIT (lighting is in the vertex colours) and the CG-only ops (GRAY, SEPIA_*: MODULATE until their programs are in)
      glTexEnvi(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_MODULATE); break;
  }
}


// ------------------------------------------------------------------------------------------------ CG programs (GRAY, SEPIA_*)
// vitaGL custom shaders: one vertex program (dqiv.v.cg) + one fragment program per op (04_SHADERS §4). Linked programs are cached as vitaGL program blobs in
// ux0:data/dqiv/cg/<name>.bin (glGetProgramBinary): with the blobs in place libshacccg is not needed at run time; without them the sources compiled into
// the executable are built with the runtime compiler (needs libshacccg.suprx; Vita3K has it) and the blob is written. If neither works the op falls back to the
// fixed-function approximation (MODULATE).
struct CgProg { GLuint prog = 0; bool tried = false; GLint uMvp[4] = {-1,-1,-1,-1}, uSlp[4] = {-1,-1,-1,-1}, uVp[4] = {-1,-1,-1,-1}, uSt = -1, uTint = -1, uBright = -1, uAtest = -1; };
static CgProg g_cg[kCgCount];                            // OP_GRAY, OP_SEPIA_FLD, OP_SLEEP
static const char* const kCgName[kCgCount] = { "dqiv_gray", "dqiv_sepia_fld", "dqiv_sleep" };
static const char* const* const kCgFrag[kCgCount] = { &kCg_dqiv_gray_f, &kCg_dqiv_sepia_fld_f, &kCg_dqiv_sleep_f };
static const char* const* const kCgVert[kCgCount] = { &kCg_dqiv_v, &kCg_dqiv_v, &kCg_dqiv_sleep_v };

static bool LinkedOk(GLuint p) { GLint ok = 0; glGetProgramiv(p, GL_LINK_STATUS, &ok); return ok != 0; }
static void BindCgAttribs(GLuint p) { glBindAttribLocation(p, 0, "position"); glBindAttribLocation(p, 1, "texcoord"); glBindAttribLocation(p, 2, "color"); }

static GLuint CompileCg(int i) {
  GLuint vs = glCreateShader(GL_CG_VERTEX_SHADER_EXT), fs = glCreateShader(GL_CG_FRAGMENT_SHADER_EXT);
  const char* vsrc = *kCgVert[i]; const char* fsrc = *kCgFrag[i];
  glShaderSource(vs, 1, &vsrc, nullptr); glCompileShader(vs);
  glShaderSource(fs, 1, &fsrc, nullptr); glCompileShader(fs);
  GLuint p = glCreateProgram();
  glAttachShader(p, vs); glAttachShader(p, fs);
  BindCgAttribs(p);
  glLinkProgram(p);
  glDeleteShader(vs); glDeleteShader(fs);
  if (!LinkedOk(p)) { glDeleteProgram(p); return 0; }
  return p;
}

static bool LoadCg(int i) {
  CgProg& c = g_cg[i];
  if (c.tried) return c.prog != 0;
  c.tried = true;
  // blob search order: the VPK (app0:cg, shipped, read-only) -> the data dir cache (ux0:data/dqiv/cg, written after a runtime compile) -> compile from the embedded source
  char path[160]; snprintf(path, sizeof(path), DATA_PATH "cg/%s.bin", kCgName[i]);
  char appPath[96]; snprintf(appPath, sizeof(appPath), "app0:cg/%s.bin", kCgName[i]);
  GLuint p = 0;
  for (const char* src : { (const char*)appPath, (const char*)path }) {
    if (p) break;
    FILE* f = fopen(src, "rb");
    if (!f) { _log_print(LT_INFO, "CG program %s: %s not found", kCgName[i], src); continue; }
    fseek(f, 0, SEEK_END); long n = ftell(f); fseek(f, 0, SEEK_SET);
    std::vector<uint8_t> blob(n > 0 ? n : 0);
    if (n > 0 && fread(blob.data(), 1, n, f) == (size_t)n) {
      p = glCreateProgram();
      glProgramBinary(p, 0, blob.data(), (GLsizei)n);
      if (!LinkedOk(p)) { _log_print(LT_INFO, "CG program %s: blob %s rejected (link failed)", kCgName[i], src); glDeleteProgram(p); p = 0; }
    }
    fclose(f);
    if (p) _log_print(LT_INFO, "CG program %s: loaded from %s", kCgName[i], src);
  }
  if (!p) {
    p = CompileCg(i);
    if (!p) { l_warn("CG program %s: compile failed (libshacccg missing?) -> fixed-function fallback", kCgName[i]); return false; }
    _log_print(LT_INFO, "CG program %s: compiled from source", kCgName[i]);
    std::vector<uint8_t> blob(128 * 1024);
    GLsizei len = 0; GLenum fmt = 0;
    glGetProgramBinary(p, (GLsizei)blob.size(), &len, &fmt, blob.data());
    sceIoMkdir(DATA_PATH "cg", 0777);
    if (len > 0) if (FILE* f = fopen(path, "wb")) { fwrite(blob.data(), 1, (size_t)len, f); fclose(f); _log_print(LT_INFO, "CG program %s: cached %d bytes in %s", kCgName[i], (int)len, path); }
  }
  c.prog = p;
  static const char* mvpn[4] = { "mvp0", "mvp1", "mvp2", "mvp3" };
  static const char* slpn[4] = { "slp0", "slp1", "slp2", "slp3" };
  static const char* vpn[4] = { "vp0", "vp1", "vp2", "vp3" };
  for (int k = 0; k < 4; k++) { c.uMvp[k] = glGetUniformLocation(p, mvpn[k]); c.uSlp[k] = glGetUniformLocation(p, slpn[k]); c.uVp[k] = glGetUniformLocation(p, vpn[k]); }
  c.uSt = glGetUniformLocation(p, "st"); c.uTint = glGetUniformLocation(p, "tint");
  c.uBright = glGetUniformLocation(p, "brightness"); c.uAtest = glGetUniformLocation(p, "atest");
  _log_print(LT_INFO, "CG program %s: uniforms mvp0 %d slp0 %d vp2 %d st %d tint %d atest %d", kCgName[i], c.uMvp[0], c.uSlp[0], c.uVp[2], c.uSt, c.uTint, c.uAtest);
  return true;
}

static std::vector<Color32> s_white32;
static std::vector<Vector2> s_zeroUv;

// Draws `dc` with the CG program of `op`; false = program unavailable (caller falls back to fixed function).
static bool DrawCg(const DrawCall& dc, const PassDesc& ps, const ShaderDesc& s, int idx) {
  if (!LoadCg(idx)) return false;
  CgProg& c = g_cg[idx];
  Matrix4x4 mvp = s.noMVP ? Matrix4x4::identity() : g_proj * g_view * dc.model;
  glUseProgram(c.prog);
  for (int k = 0; k < 4; k++) if (c.uMvp[k] >= 0) { const float* m = mvp.m; float row[4] = { m[k], m[4 + k], m[8 + k], m[12 + k] }; glUniform4fv(c.uMvp[k], 1, row); }
  float sx = s.st ? dc.stScale.x : 1.f, sy = s.st ? dc.stScale.y : 1.f, ox = s.st == 2 ? dc.stOffset.x : 0.f, oy = s.st == 2 ? dc.stOffset.y : 0.f;
  if (c.uSt >= 0) { float st[4] = { sx, sy, ox, oy }; glUniform4fv(c.uSt, 1, st); }
  Color tint = s.useTint ? dc.tint : Color::white;
  if (c.uTint >= 0) { float t[4] = { tint.r, tint.g, tint.b, tint.a }; glUniform4fv(c.uTint, 1, t); }
  if (c.uBright >= 0) glUniform1f(c.uBright, dc.brightness);
  if (c.uAtest >= 0) glUniform1f(c.uAtest, ps.atest == AT_EQUAL1 && ps.op == OP_SLEEP ? 2.f : ps.atest != AT_NONE ? 1.f : 0.f);
  if (ps.op == OP_SLEEP) {                               // _sleepMatrix and the view-projection rows that give z/w
    Matrix4x4 vp = g_proj * g_view;
    for (int k = 0; k < 4; k++) {
      const float* m = dc.sleepMatrix.m; float row[4] = { m[k], m[4 + k], m[8 + k], m[12 + k] };
      if (c.uSlp[k] >= 0) glUniform4fv(c.uSlp[k], 1, row);
      const float* v = vp.m; float rv[4] = { v[k], v[4 + k], v[8 + k], v[12 + k] };
      if (c.uVp[k] >= 0) glUniform4fv(c.uVp[k], 1, rv);
    }
  }

  glEnable(GL_TEXTURE_2D);
  BindTex(dc.texture ? dc.texture : s_white);
  g_stats.progSwitches++;
  glDisableClientState(GL_VERTEX_ARRAY); glDisableClientState(GL_TEXTURE_COORD_ARRAY); glDisableClientState(GL_COLOR_ARRAY);
  const Color32* col = s.useVertexColor ? dc.colors : nullptr;
  if (!col) { if ((int)s_white32.size() < dc.vertexCount) s_white32.assign(dc.vertexCount, Color32(255, 255, 255, 255)); col = s_white32.data(); }
  const Vector2* uv = dc.uvs;
  if (!uv) { if ((int)s_zeroUv.size() < dc.vertexCount) s_zeroUv.assign(dc.vertexCount, Vector2(0, 0)); uv = s_zeroUv.data(); }
  glEnableVertexAttribArray(0); glEnableVertexAttribArray(1); glEnableVertexAttribArray(2);
  glVertexAttribPointer(0, 3, GL_FLOAT, GL_FALSE, sizeof(Vector3), dc.positions);
  glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, sizeof(Vector2), uv);
  glVertexAttribPointer(2, 4, GL_UNSIGNED_BYTE, GL_TRUE, sizeof(Color32), col);

  s_idx.resize(dc.indexCount);
  int maxIdx = 0;
  for (int i = 0; i < dc.indexCount; i++) { int v = dc.indices[i]; maxIdx = v > maxIdx ? v : maxIdx; s_idx[i] = (uint16_t)v; }
  if (maxIdx < dc.vertexCount && maxIdx < 65536) glDrawElements(GL_TRIANGLES, dc.indexCount, GL_UNSIGNED_SHORT, s_idx.data());
  glDisableVertexAttribArray(0); glDisableVertexAttribArray(1); glDisableVertexAttribArray(2);
  glUseProgram(0);
  return true;
}

static inline uint8_t Mul8(uint8_t a, float t) { float v = a * t + 0.5f; return v >= 255.f ? 255 : v <= 0.f ? 0 : (uint8_t)v; }

// ---- GL buffer objects for immutable pack meshes (FLD maps, fbx models): uploaded once, drawn without per-frame copies of the vertex arrays into vitaGL's pool.
static size_t g_vboBytes = 0;
static constexpr size_t kVboBudget = 24u * 1024 * 1024;       // vitaGL pool bytes spent on static buffers; beyond that meshes keep using client arrays
static void FreeMeshBuffers(unsigned vbo, const std::vector<unsigned>& ibo) {
  if (vbo) { GLuint b = vbo; glDeleteBuffers(1, &b); }
  for (unsigned i : ibo) if (i) { GLuint b = i; glDeleteBuffers(1, &b); }
}
static bool EnsureMeshBuffers(const Mesh* m) {
  Mesh::GpuCache& g = m->gpu;
  if (g.vbo) return true;
  if (g.vboFail) return false;
  size_t n = m->vertices.size();
  bool uv = m->uv.size() == n, col = m->colors32.size() == n;
  int stride = 12 + (uv ? 8 : 0) + (col ? 4 : 0);
  size_t idxBytes = 0; for (auto& t : m->subTriangles) idxBytes += t.size() * 2;
  if (n < 16 || n > 65535 || !m->colors.empty() || g_vboBytes + n * stride + idxBytes > kVboBudget) { g.vboFail = 1; return false; }
  std::vector<uint8_t> buf(n * stride);
  for (size_t i = 0; i < n; i++) {
    uint8_t* p = &buf[i * stride];
    memcpy(p, &m->vertices[i], 12); p += 12;
    if (uv) { memcpy(p, &m->uv[i], 8); p += 8; }
    if (col) memcpy(p, &m->colors32[i], 4);
  }
  GLuint vbo = 0; glGenBuffers(1, &vbo);
  glBindBuffer(GL_ARRAY_BUFFER, vbo);
  glBufferData(GL_ARRAY_BUFFER, (GLsizei)buf.size(), buf.data(), GL_STATIC_DRAW);
  glBindBuffer(GL_ARRAY_BUFFER, 0);
  g.vbo = vbo; g.vboVerts = (int)n; g.vboStride = stride; g.vboUv = uv; g.vboCol = col;
  g.ibo.assign(m->subTriangles.size() + 1, 0);            // + the tinted-colour buffer slot
  for (size_t k = 0; k < m->subTriangles.size(); k++) {
    if (k >= g.idx16.size() || g.idx16[k].empty()) continue;
    GLuint ib = 0; glGenBuffers(1, &ib);
    glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, ib);
    glBufferData(GL_ELEMENT_ARRAY_BUFFER, (GLsizei)(g.idx16[k].size() * 2), g.idx16[k].data(), GL_STATIC_DRAW);
    glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, 0);
    g.ibo[k] = ib;
  }
  g_vboBytes += buf.size() + idxBytes;
  s_arrayBuf = 0;
  return true;
}

static void ApplyPassState(const PassDesc& ps) {
  if (s_psValid && memcmp(&s_lastPs, &ps, sizeof(PassDesc)) == 0) return;
  s_lastPs = ps; s_psValid = true;
  if (ps.cull) { glEnable(GL_CULL_FACE); glCullFace(GL_BACK); } else glDisable(GL_CULL_FACE);
  glDepthMask(ps.zwrite ? GL_TRUE : GL_FALSE);
  glEnable(GL_DEPTH_TEST);
  glDepthFunc(ps.ztest == CMP_ALWAYS ? GL_ALWAYS : ps.ztest == CMP_LEQUAL ? GL_LEQUAL : GL_LESS);
  if (ps.blend) { glEnable(GL_BLEND); glBlendFunc(GL_SRC_ALPHA, ps.blend == BLEND_ADD ? GL_ONE : GL_ONE_MINUS_SRC_ALPHA); } else glDisable(GL_BLEND);
  if (ps.atest == AT_GREATER0)    { glEnable(GL_ALPHA_TEST); glAlphaFunc(GL_GREATER, 0.0f); }
  else if (ps.atest == AT_EQUAL1) { glEnable(GL_ALPHA_TEST); glAlphaFunc(GL_EQUAL, 1.0f); }
  else glDisable(GL_ALPHA_TEST);
  glColorMask((ps.colorMask & 1) != 0, (ps.colorMask & 2) != 0, (ps.colorMask & 4) != 0, (ps.colorMask & 8) != 0);
}

void Draw(const DrawCall& dc) {
  const ShaderDesc& s = *dc.sd;
  const PassDesc& ps = s.pass[dc.pass < s.npass ? dc.pass : 0];
  if (dc.vertexCount <= 0 || dc.indexCount <= 0) return;
  g_stats.draws++; g_stats.indices += dc.indexCount;
  int shi = ShaderId(dc.sd); if (shi < 0 || shi > 63) shi = 63;
  g_stats.shDraws[shi]++;

  ApplyPassState(ps);

  static const bool sleepCg = Cfg::GetInt("sleep_cg", 1) != 0;     // cfg sleep_cg=0: draw CharaSleep with the fixed-function MODULATE fallback (debug)
  if (ps.op == OP_GRAY || ps.op == OP_SEPIA_FLD || (ps.op == OP_SLEEP && sleepCg)) {
    if (DrawCg(dc, ps, s, ps.op == OP_GRAY ? 0 : ps.op == OP_SEPIA_FLD ? 1 : 2)) return;
  }
  // ---- matrices (model; view/projection were loaded by BeginCamera). Clip-space shaders ignore all of them.
  glMatrixMode(GL_MODELVIEW);
  glPushMatrix();
  if (s.noMVP) {
    glMatrixMode(GL_PROJECTION); glPushMatrix(); glLoadIdentity();
    glMatrixMode(GL_MODELVIEW);  glLoadIdentity();
  } else {
    glMultMatrixf(dc.model.m);
  }

  // ---- texture: a missing texture samples white in Unity (tex*C == C for MUL/A8; INV_A then yields alpha 0)
  bool textured = ps.op != OP_FLAT && dc.uvs && (dc.texture || ps.op == OP_INV_A || ps.op == OP_POST_A || ps.op == OP_INVERT || ps.op == OP_RGB_A1);
  if (textured) {
    glEnable(GL_TEXTURE_2D);
    BindTex(dc.texture ? dc.texture : s_white);
    SetupTexEnv(ps.op);
  } else {
    glDisable(GL_TEXTURE_2D);
  }

  Color tint = s.useTint && ps.op != OP_INVERT ? dc.tint : Color::white;
  bool tinted = tint.r != 1.f || tint.g != 1.f || tint.b != 1.f || tint.a != 1.f;
  float sx = s.st ? dc.stScale.x : 1.f, sy = s.st ? dc.stScale.y : 1.f, ox = s.st == 2 ? dc.stOffset.x : 0.f, oy = s.st == 2 ? dc.stOffset.y : 0.f;
  bool stId = sx == 1.f && sy == 1.f && ox == 0.f && oy == 0.f;

  // ---- buffer-object path: immutable pack mesh, no CPU work needed per draw
  const Mesh* mesh = dc.mesh;
  int why = !mesh ? 0 : mesh->packId == 0 ? 1 : mesh->instanceOwner ? 2 : mesh->dynamic ? 3 : !stId ? 4 : 7;
  bool vbo = why == 7 && dc.indices16 && dc.maxIndex >= 0 && dc.maxIndex < dc.vertexCount && EnsureMeshBuffers(mesh);
  if (why == 7 && !vbo) why = 5;
  if (vbo) {
    const Mesh::GpuCache& g = mesh->gpu;
    bool useCol = s.useVertexColor && g.vboCol;
    if (useCol && tinted) {
      // tinted vertex colours (FLD map colour rate, fades): a tinted copy of the colour array is cached per mesh while the tint stays unchanged for 3+ draws; animated tints use client arrays
      Mesh::GpuCache& gm = mesh->gpu;
      if (!(gm.tintKey.r == tint.r && gm.tintKey.g == tint.g && gm.tintKey.b == tint.b && gm.tintKey.a == tint.a)) {
        gm.tintKey = tint; gm.tintStable = 0;
        if (gm.ibo.back()) { GLuint b = gm.ibo.back(); glDeleteBuffers(1, &b); gm.ibo.back() = 0; }
      } else if (gm.tintStable < 1000) gm.tintStable++;
      if (gm.tintStable >= 3 && !gm.ibo.back()) {
        std::vector<Color32> tc(mesh->colors32.size());
        for (size_t i = 0; i < tc.size(); i++) tc[i] = Color32(Mul8(mesh->colors32[i].r, tint.r), Mul8(mesh->colors32[i].g, tint.g), Mul8(mesh->colors32[i].b, tint.b), Mul8(mesh->colors32[i].a, tint.a));
        GLuint cb = 0; glGenBuffers(1, &cb); glBindBuffer(GL_ARRAY_BUFFER, cb);
        glBufferData(GL_ARRAY_BUFFER, (GLsizei)(tc.size() * 4), tc.data(), GL_STATIC_DRAW); glBindBuffer(GL_ARRAY_BUFFER, 0);
        gm.ibo.back() = cb;
      }
      if (!gm.ibo.back()) { why = 6; vbo = false; }
    }
    if (vbo && ((textured && !g.vboUv) || dc.sub >= (int)g.ibo.size() - 1 || !g.ibo[dc.sub] || g.vboVerts != dc.vertexCount)) vbo = false;
  }
  if (!vbo) g_stats.vboWhy[why]++;
  if (vbo) {
    const Mesh::GpuCache& g = mesh->gpu;
    bool useCol = s.useVertexColor && g.vboCol;
    glBindBuffer(GL_ARRAY_BUFFER, g.vbo);
    glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, g.ibo[dc.sub]);
    glEnableClientState(GL_VERTEX_ARRAY);
    glVertexPointer(3, GL_FLOAT, g.vboStride, (const void*)0);
    if (textured) { glEnableClientState(GL_TEXTURE_COORD_ARRAY); glTexCoordPointer(2, GL_FLOAT, g.vboStride, (const void*)12); } else glDisableClientState(GL_TEXTURE_COORD_ARRAY);
    if (useCol && tinted) {
      glBindBuffer(GL_ARRAY_BUFFER, g.ibo.back());
      glEnableClientState(GL_COLOR_ARRAY); glColorPointer(4, GL_UNSIGNED_BYTE, 4, (const void*)0);
      glBindBuffer(GL_ARRAY_BUFFER, g.vbo);
      g_stats.tintCached++;
    }
    else if (useCol) { glEnableClientState(GL_COLOR_ARRAY); glColorPointer(4, GL_UNSIGNED_BYTE, g.vboStride, (const void*)(12 + (g.vboUv ? 8 : 0))); }
    else { glDisableClientState(GL_COLOR_ARRAY); glColor4f(tint.r, tint.g, tint.b, tint.a); }
    glDrawElements(GL_TRIANGLES, dc.indexCount, GL_UNSIGNED_SHORT, (const void*)0);
    glBindBuffer(GL_ARRAY_BUFFER, 0);
    glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, 0);
    g_stats.vboDraws++;
  } else {
    // ---- client arrays
    glEnableClientState(GL_VERTEX_ARRAY);
    glVertexPointer(3, GL_FLOAT, sizeof(Vector3), dc.positions);
    g_stats.clientArrayBytes += dc.vertexCount * (int)sizeof(Vector3); g_stats.shVerts[shi] += dc.vertexCount;
    if (textured) {
      const Vector2* uv = dc.uvs;
      if (!stId) {
        s_uv.resize(dc.vertexCount);
        for (int i = 0; i < dc.vertexCount; i++) s_uv[i] = Vector2(dc.uvs[i].x * sx + ox, dc.uvs[i].y * sy + oy);
        uv = s_uv.data();
      }
      glEnableClientState(GL_TEXTURE_COORD_ARRAY);
      glTexCoordPointer(2, GL_FLOAT, sizeof(Vector2), uv);
      g_stats.clientArrayBytes += dc.vertexCount * (int)sizeof(Vector2);
    } else {
      glDisableClientState(GL_TEXTURE_COORD_ARRAY);
    }
    // C = vertexColor * _Color (the parts the shader has); white where the mesh has no colours (Unity default attribute)
    if (s.useVertexColor && dc.colors) {
      const Color32* col = dc.colors;
      if (tinted) {
        s_col.resize(dc.vertexCount);
        for (int i = 0; i < dc.vertexCount; i++)
          s_col[i] = Color32(Mul8(dc.colors[i].r, tint.r), Mul8(dc.colors[i].g, tint.g), Mul8(dc.colors[i].b, tint.b), Mul8(dc.colors[i].a, tint.a));
        col = s_col.data();
        g_stats.cpuColorMul++; g_stats.shMul[shi]++;
      }
      glEnableClientState(GL_COLOR_ARRAY);
      glColorPointer(4, GL_UNSIGNED_BYTE, sizeof(Color32), col);
      g_stats.clientArrayBytes += dc.vertexCount * (int)sizeof(Color32);
    } else {
      glDisableClientState(GL_COLOR_ARRAY);
      glColor4f(tint.r, tint.g, tint.b, tint.a);
    }
    // ---- indices (u16)
    const uint16_t* idx = dc.indices16; int maxIdx = dc.maxIndex;
    if (!idx) {
      s_idx.resize(dc.indexCount);
      maxIdx = 0;
      for (int i = 0; i < dc.indexCount; i++) { int v = dc.indices[i]; maxIdx = v > maxIdx ? v : maxIdx; s_idx[i] = (uint16_t)v; }
      idx = s_idx.data();
      g_stats.idxConvert++;
    }
    g_stats.clientArrayBytes += dc.indexCount * 2;
    if (maxIdx < dc.vertexCount && maxIdx < 65536) glDrawElements(GL_TRIANGLES, dc.indexCount, GL_UNSIGNED_SHORT, idx);   // stale triangle lists must not read past the vertex arrays
  }

  if (s.noMVP) { glMatrixMode(GL_PROJECTION); glPopMatrix(); }
  glMatrixMode(GL_MODELVIEW);
  glPopMatrix();
}

void EndFrameAndPresent() {
  // blit the logical surface, centred, onto the display
  if (g_boundFbo != 0) { glBindFramebuffer(GL_FRAMEBUFFER, 0); g_boundFbo = 0; }
  glViewport(0, 0, DQIV_DISPLAY_W, DQIV_DISPLAY_H);
  glDisable(GL_SCISSOR_TEST);
  glDisable(GL_DEPTH_TEST); glDepthMask(GL_FALSE);
  glDisable(GL_CULL_FACE); glDisable(GL_BLEND); glDisable(GL_ALPHA_TEST);
  glClearColor(0, 0, 0, 1);
  glClear(GL_COLOR_BUFFER_BIT);                       // pillars

  glMatrixMode(GL_PROJECTION); glLoadIdentity(); glOrthof(0, DQIV_DISPLAY_W, 0, DQIV_DISPLAY_H, -1, 1);
  glMatrixMode(GL_MODELVIEW);  glLoadIdentity();
  glEnable(GL_TEXTURE_2D);
  glBindTexture(GL_TEXTURE_2D, g_fboTex);
  glTexEnvi(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_REPLACE);
  float x0 = (float)g_viewX0, x1 = (float)(g_viewX0 + g_viewW), y0 = (float)g_viewY0, y1 = (float)(g_viewY0 + g_viewH);
  const float v[8] = { x0, y0,  x1, y0,  x0, y1,  x1, y1 };
  const float t[8] = { 0, 0,  1, 0,  0, 1,  1, 1 };
  glEnableClientState(GL_VERTEX_ARRAY); glEnableClientState(GL_TEXTURE_COORD_ARRAY); glDisableClientState(GL_COLOR_ARRAY);
  glVertexPointer(2, GL_FLOAT, 0, v);
  glTexCoordPointer(2, GL_FLOAT, 0, t);
  glColor4f(1, 1, 1, 1);
  glDrawArrays(GL_TRIANGLE_STRIP, 0, 4);
  glTexEnvi(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_MODULATE);
  glDisable(GL_TEXTURE_2D);
  InvalidateGlState();

  vglSwapBuffers(dqiv_common_dialog_active ? GL_TRUE : GL_FALSE);    // WP3: sceMsgDialog (ApplicationQuit) needs the common-dialog swap
}

void CopyTargetTo(unsigned tex, int w, int h) {
  glBindTexture(GL_TEXTURE_2D, tex); s_boundTex = ~0u;
  glCopyTexSubImage2D(GL_TEXTURE_2D, 0, 0, 0, 0, 0, std::min(w, g_tgtW), std::min(h, g_tgtH));
}

static int g_blitX, g_blitY, g_blitW = 0, g_blitH;
void SetBlitRect(int x, int y, int w, int h) { g_blitX = x; g_blitY = y; g_blitW = w; g_blitH = h; }
void BlitFullscreen(unsigned srcTex, const ShaderDesc* sd, Color tint, float brightness) {
  static const Vector3 pos[4] = { Vector3(-1, -1, 0), Vector3(1, -1, 0), Vector3(1, 1, 0), Vector3(-1, 1, 0) };
  static const Vector2 uv[4] = { Vector2(0, 0), Vector2(1, 0), Vector2(1, 1), Vector2(0, 1) };
  static const int idx[6] = { 0, 2, 1, 0, 3, 2 };
  glViewport(0, 0, g_tgtW, g_tgtH);
  glEnable(GL_SCISSOR_TEST);
  if (g_blitW > 0) glScissor(g_blitX, g_blitY, g_blitW, g_blitH); else glScissor(0, 0, g_tgtW, g_tgtH);     // full-target quad, clipped to the camera rect: the texel under each pixel is the one the camera rendered there
  glMatrixMode(GL_PROJECTION); glLoadIdentity(); glMatrixMode(GL_MODELVIEW); glLoadIdentity();
  DrawCall dc{};
  dc.sd = sd; dc.texture = srcTex; dc.tint = tint; dc.brightness = brightness; dc.stScale = Vector2(1, 1);
  dc.positions = pos; dc.uvs = uv; dc.colors = nullptr; dc.vertexCount = 4; dc.indices = idx; dc.indexCount = 6; dc.model = Matrix4x4::identity();
  for (int p = 0; p < sd->npass; p++) { dc.pass = p; Draw(dc); }
}

// ------------------------------------------------------------------------------------------------ textures
unsigned CreateTexture(int w, int h, int packFormat, const void* pixels) { return MakeTexture(w, h, packFormat, pixels); }
void UpdateTexture(unsigned id, int w, int h, int packFormat, const void* pixels) {
  glBindTexture(GL_TEXTURE_2D, id); s_boundTex = ~0u;
  GLenum f = GL_RGBA, type = GL_UNSIGNED_BYTE;
  switch (packFormat) {
    case DQIV_TF_A8: f = GL_ALPHA; break;
    case DQIV_TF_RGB565: f = GL_RGB; type = GL_UNSIGNED_SHORT_5_6_5; break;
    case DQIV_TF_RGBA4444: type = GL_UNSIGNED_SHORT_4_4_4_4; break;
    default: break;
  }
  glTexSubImage2D(GL_TEXTURE_2D, 0, 0, 0, w, h, f, type, pixels);
}
void DeleteTexture(unsigned id) { GLuint i = id; glDeleteTextures(1, &i); }
void SetTextureSampler(unsigned id, int filter, int wrap) {
  glBindTexture(GL_TEXTURE_2D, id); s_boundTex = ~0u;
  GLint mag = filter == 0 ? GL_NEAREST : GL_LINEAR;
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, mag);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, mag);
  GLint w = wrap == 0 ? GL_REPEAT : GL_CLAMP_TO_EDGE;
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, w);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, w);
}
bool CreateRenderTexture(int w, int h, unsigned* fbo, unsigned* colorTex, unsigned* depthRb) {
  GLuint f = 0, t = 0, d = 0;
  glGenFramebuffers(1, &f);
  glBindFramebuffer(GL_FRAMEBUFFER, f);
  glGenTextures(1, &t);
  glBindTexture(GL_TEXTURE_2D, t);
  glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, w, h, 0, GL_RGBA, GL_UNSIGNED_BYTE, nullptr);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
  glFramebufferTexture2D(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, t, 0);
  glGenRenderbuffers(1, &d);
  glBindRenderbuffer(GL_RENDERBUFFER, d);
  glRenderbufferStorage(GL_RENDERBUFFER, GL_DEPTH_COMPONENT16, w, h);
  glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_DEPTH_ATTACHMENT, GL_RENDERBUFFER, d);
  glBindFramebuffer(GL_FRAMEBUFFER, g_boundFbo);
  *fbo = f; *colorTex = t; *depthRb = d;
  return true;
}
void DestroyRenderTexture(unsigned fbo, unsigned colorTex, unsigned depthRb) {
  GLuint f = fbo, t = colorTex, d = depthRb;
  glDeleteFramebuffers(1, &f); glDeleteTextures(1, &t); glDeleteRenderbuffers(1, &d);
}

