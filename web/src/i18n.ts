const DICTS: Record<string, Dict> = { en, es };
let cur = "en";
try { const s = localStorage.getItem("dqiv-ui-lang"); cur = s && DICTS[s] ? s : navigator.language.toLowerCase().startsWith("es") ? "es" : "en"; } catch { /* no storage */ }

export const uiLang = () => cur;
export function setUiLang(l: string) { cur = l; try { localStorage.setItem("dqiv-ui-lang", l); } catch { /* ignore */ } apply(); }
export function t(key: string, p: Record<string, string | number> = {}): string {
  const s = DICTS[cur][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(p[k] ?? ""));
}
export function apply() {
  document.documentElement.lang = cur;
  for (const el of document.querySelectorAll<HTMLElement>("[data-i18n]")) el.innerHTML = t(el.dataset.i18n!);   // strings are ours, never user input
  document.title = t("title");
}
