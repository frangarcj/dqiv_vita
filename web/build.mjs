// Build: web/src/*.ts -> web/dist/app.js (esbuild; committed) and web/test/.dist (node harness; ignored). `node build.mjs` ; `node build.mjs --check` also type-checks with tsc.
import { build } from "esbuild";
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const p = (...a) => join(here, ...a);

// 1. the precompiled GPU programs of the screen-effect shaders live in extras/cg of the repo: embed them (works offline and from file://)
const cgDir = p("..", "extras", "cg");
const cg = readdirSync(cgDir).filter(f => f.endsWith(".bin")).sort();
writeFileSync(p("src", "cgdata.ts"),
  "// GENERATED by build.mjs from extras/cg/*.bin -- do not edit.\n" +
  "const b64 = (s: string) => Uint8Array.from(atob(s), c => c.charCodeAt(0));\n" +
  "export const CG_FILES: Record<string, Uint8Array> = {\n" +
  cg.map(f => `  ${JSON.stringify(f)}: b64(${JSON.stringify(readFileSync(join(cgDir, f)).toString("base64"))}),\n`).join("") + "};\n");

if (process.argv.includes("--check")) execFileSync(p("node_modules", ".bin", "tsc"), ["-p", here, "--noEmit"], { stdio: "inherit" });

mkdirSync(p("dist"), { recursive: true });
const common = { bundle: true, format: "esm", target: "es2022", legalComments: "none", logLevel: "info" };

// 2. the worker is bundled first and inlined into the page script as text (a Blob URL worker also starts from file:// and any origin)
const w = await build({ ...common, entryPoints: [p("src", "worker.browser.ts")], write: false, minify: true, format: "iife" });
const workerSrc = w.outputFiles[0].text;
await build({ ...common, entryPoints: [p("src", "main.ts")], outfile: p("dist", "app.js"), minify: true, format: "iife",
  define: { __WORKER_SRC__: JSON.stringify(workerSrc) } });

// 3. Node test harness bundle (worker_threads worker + driver), not committed
await build({ ...common, entryPoints: { "node-worker": p("src", "worker.node.ts"), "node-run": p("src", "node-run.ts") }, outdir: p("test", ".dist"),
  platform: "node", minify: false, format: "esm", outExtension: { ".js": ".mjs" } });
console.log("built web/dist (page) and web/test/.dist (node harness)");
