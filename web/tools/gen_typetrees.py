#!/usr/bin/env python3
"""Dev tool (not needed to build or use the page): regenerate web/src/typetrees.ts.

The Unity 4.7.2 serialized files of Dragon Quest IV carry NO type trees (stripped player build), so the reference converter's reader (UnityPy)
takes them from its built-in class database for the editor version 4.7.2f1.  This script dumps the release type trees of every class that
occurs in the game's files, as compact JSON, so that the web converter needs no external database.

    python3 -I web/tools/gen_typetrees.py <unity_root>        # a directory holding mainData, level0, sharedassets*, obb_data/ (see tools/make_data.py stage_unity)
needs the packages of tools/requirements.txt (UnityPy 1.25.4).
"""
import json, os, sys
import UnityPy
from UnityPy.helpers.Tpk import get_typetree_node
from UnityPy.helpers.UnityVersion import UnityVersion

root = sys.argv[1]
files = [os.path.join(root, n) for n in ("mainData", "level0", "sharedassets0.assets", "sharedassets1.assets")]
files += [os.path.join(root, "obb_data", n) for n in sorted(os.listdir(os.path.join(root, "obb_data"))) if n not in ("level0", "sharedassets1.assets")]
classes = {}
for p in files:
    sf = list(UnityPy.load(p).files.values())[0]
    assert not sf.types, "this file carries its own type trees: the web reader would have to use them"
    for o in sf.objects.values():
        classes[o.class_id] = o.type.name
ver = UnityVersion.from_str("4.7.2f1")

def dump(n):
    return [n.m_Type, n.m_Name, n.m_MetaFlag] + ([[dump(c) for c in n.m_Children]] if n.m_Children else [])

out = {}
for cid in sorted(classes):
    try:
        out[cid] = dump(get_typetree_node(cid, ver))
    except Exception as e:
        print("no type tree for", cid, classes[cid], e, file=sys.stderr)
js = json.dumps(out, separators=(",", ":"))
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "..", "src", "typetrees.ts"), "w") as f:
    f.write("// GENERATED by web/tools/gen_typetrees.py (UnityPy 1.25.4 class database, Unity 4.7.2f1 release trees) -- do not edit.\n"
            "// class id -> [type, name, metaFlag, children?] ; the game's serialized files carry no type trees of their own.\n"
            "export const TYPE_TREES: Record<string, any> = JSON.parse(%s);\n" % json.dumps(js))
print(len(out), "classes,", len(js), "bytes of JSON:", {cid: classes[cid] for cid in out})
