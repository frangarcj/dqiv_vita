#!/usr/bin/env python3
"""Generates the scripts of the long-session soak for DQ4 (see DEVELOPERS.md "Soak test"):
     tools/soak/make_soak.py <iterations> <ready_frame> [--input FILE] > warp.on
Each iteration (2280 frames, ~76 s of game time at 30 fps): warp into a town / dungeon of the chapter-5 party (480 f) -> force a battle on another stage with a pad script
that fights it (Cross taps drive Fight / Attack / first target, 1320 f) -> world map (480 f).  The UI soak (cfg `ui_soak=300:0`) can run in parallel.
Needs the WarpTest harness (`warp<slot>.on`, game/WarpTest.hpp) and `input_script=1` for the pad taps.  ready_frame = frame at which MainLoop is ready (log: "MainLoop: running").
The party is the chapter-5 event 289 (party of 3, level 31) with nodamage + 99999 gold so every battle ends in victory."""
import sys
TOWNS = ["maout", "mfout", "dab1", "cdout", "hcout", "mhg1n1", "ceout", "dpb1a", "mnout"]
STAGES = ["btl_pl_d", "btl_mt_d", "btlda1", "btl_wd_d", "btl_sd_e", "btlcb1_d"]
MONS = ["1x2", "2x1 3x1", "5x2", "8x1", "10x2 1x1", "3x3"]
def main():
    n = int(sys.argv[1]); ready = int(sys.argv[2]); inp = sys.argv[sys.argv.index("--input") + 1] if "--input" in sys.argv else None
    delay = 150
    print("delay %d\neventinit 289\ntown maout\ngold 99999\nnodamage 1\nnoencount 1\nwait 300" % delay)
    taps = []
    f = ready + delay + 300 + 5
    for i in range(n):
        print("town %s\nwait 480" % TOWNS[i % len(TOWNS)])
        print("battle %s %s\nwait 1320" % (STAGES[i % len(STAGES)], MONS[i % len(MONS)]))
        bstart = f + 480
        taps.append((bstart + 200, bstart + 1300, 24))            # Cross every 24 frames: Fight -> Attack -> target -> message advance
        print("field\nwait 480")
        f += 2280
    print("wait 600")
    if inp:
        with open(inp, "w") as o:
            o.write("# generated by tools/soak/make_soak.py: battle Cross taps\n")
            for a, b, p in taps: o.write("%d-%d/%d tap cross\n" % (a, b, p))
            o.write("%d quit\n" % (f + 900))
main()
