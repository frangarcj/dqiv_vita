#!/usr/bin/env python3
"""Generates the scripts of the long-session soak (see DEVELOPERS.md "Soak test"):
     tools/soak/make_soak.py <iterations> <ready_frame> > warp.on ; also writes input_script.txt next to it (--input FILE)
Each iteration (2280 frames, ~76 s of game time): warp into a town / dungeon / world map (480 f), force a battle on another stage with scripted touches that
fight it (1320 f), world map (480 f).  The UI soak (cfg `ui_soak=300:0`) runs in parallel.
Needs the WarpTest harness (WP1, `warp<slot>.on`) and the input script (`input_script=1`).  ready_frame = frame at which MainLoop is ready (log: "MainLoop: running")."""
import sys
TOWNS = ["maout1", "mayf1", "dkb1", "ma2f1", "mawf1", "mak", "ev01", "swlv3a", "caout1"]
STAGES = ["btlca1", "btl_pl_d", "btl_mt_d", "btl_is_d", "btl_po_d", "btl_dk1"]
MONS = ["1x2", "2x1 3x1", "5x2", "8x1", "10x2 1x1", "3x3"]
def main():
    n = int(sys.argv[1]); ready = int(sys.argv[2]); inp = sys.argv[sys.argv.index("--input") + 1] if "--input" in sys.argv else None
    delay = 150
    print("delay %d\nchapter 4\ngold 99999" % delay)
    touches = []
    f = ready + delay + 5
    for i in range(n):
        print("town %s\nwait 480" % TOWNS[i % len(TOWNS)])
        print("battle %s %s\nwait 1320" % (STAGES[i % len(STAGES)], MONS[i % len(MONS)]))
        bstart = f + 480
        for r in range(6):                       # up to 6 rounds: Fight, Attack, two target taps, message advance
            t = bstart + 150 + r * 130
            touches += [(t, 224, 165), (t + 25, 104, 165), (t + 50, 104, 166), (t + 70, 104, 120), (t + 100, 204, 144)]
        print("field\nwait 480")
        f += 2280
    print("wait 600")
    if inp:
        with open(inp, "w") as o:
            o.write("# generated by tools/soak/make_soak.py: battle touches (UI panel pixels)\n")
            for t, x, y in touches: o.write("%d touch %d %d\n" % (t, x, y))
            o.write("%d quit\n" % (f + 900))
main()
